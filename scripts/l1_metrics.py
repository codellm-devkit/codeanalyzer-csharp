#!/usr/bin/env python3
# L1 symbol-table metrics for codeanalyzer-csharp (cansharp).
#
# Self-validating: reads an emitted analysis.json and compares it against the canonical
# schema v2 invariants and its own internal consistency. No external oracle, no ground truth
# (the opt-in Roslyn oracle layer is a separate tool). Mirrors the house convention from
# codeanalyzer-go/scripts/l3_metrics.py: descriptive distributions + a check_failures dict
# that lists ONLY nonzero invariant violations. Emits JSONL, one object per input, to stdout.
#
# Pass/fail is the SHELL's job (eval_l1.sh): a clean run has check_failures == {}.
#
# Usage (run isolated, per the environment's untrusted-data guidance):
#   python3 -I scripts/l1_metrics.py LABEL=path/to/analysis.json [LABEL=PATH ...] > metrics.jsonl
#
# Memory: each file is loaded whole via json.load (a large analysis.json needs headroom).

import json
import os
import re
import sys

SCHEMA_VERSION = "2.0.0"
IDENTITY_VERSION = 2
LANGUAGE = "csharp"
MAX_LEVEL = 1

# can://<namespace>/<application>/csharp/<rest...> — the two-segment root (python-sdk#440).
# ns and app are percent-encoded raw strings (#435); the language token is fixed.
ID_ROOT_RE = re.compile(r"^can://[^/]+/[^/]+/csharp(?:/.+)?$")

TYPE_KINDS = {"class", "struct", "interface", "enum", "record", "record_struct", "delegate"}
FIELD_KINDS = {"field", "property", "event"}
REF_KINDS = {"ref", "out", "in", "ref_readonly"}

# The locked L1 decisions whose firing we track as a breadth checklist.
DECISION_PROBES = [
    "record", "record_struct", "delegate",           # D-records / D-delegate (type kinds)
    "property", "event",                              # D-props (field kinds)
    "accessor_get", "accessor_set",                   # D-props (#get / #set callables)
    "ref", "out", "in", "ref_readonly",               # D-refkind
    "is_async", "is_iterator",                        # D-async
    "parts",                                          # D6 partial-type merge
    "nested_type", "generic_type",                    # containment / arity in id
]


def file_class(path, source_head):
    """Descriptive generated-file classifier (locked). Breakdown only; excludes nothing."""
    base = path.rsplit("/", 1)[-1]
    if path.endswith(".Designer.cs"):
        return "designer"
    if path.endswith(".xaml.cs"):
        return "xaml_codebehind"
    if base == "AssemblyInfo.cs" or path.endswith("GlobalUsings.g.cs") \
            or path.endswith(".AssemblyAttributes.cs"):
        return "assembly_info"
    if path.endswith((".g.cs", ".generated.cs", ".i.cs", ".razor.cs")) \
            or "<auto-generated" in source_head \
            or "GeneratedCodeAttribute" in source_head:
        return "generated"
    return "hand_written"


def pct(xs, q):
    """Nearest-rank percentile on a sorted list (same shape as the Go script's pct)."""
    if not xs:
        return 0
    return xs[min(len(xs) - 1, int(q * (len(xs) - 1) + 0.5))]


def distribution(values):
    """median/p90/p99/max/zero for a list of ints."""
    s = sorted(values)
    return {
        "median": pct(s, 0.50),
        "p90": pct(s, 0.90),
        "p99": pct(s, 0.99),
        "max": s[-1] if s else 0,
        "zero": sum(1 for v in values if v == 0),
        "n": len(values),
    }


def iter_types(type_node, parent_is_type=False):
    """Yield (type_node, is_nested). L1 emits types flat under module today; this still
    future-proofs for nested types once they are homed under their container."""
    yield type_node, parent_is_type
    for nested in (type_node.get("types") or {}).values():
        yield from iter_types(nested, parent_is_type=True)


class L1Analyzer:
    def __init__(self, label, path):
        self.label = label
        self.path = path
        self.C = {}          # scalar counters
        self.K = {}          # keyed breakdowns (Counter-like dicts)
        self.chk = {}        # check_failures (nonzero only, filtered at the end)
        self.decisions = {k: False for k in DECISION_PROBES}
        self._ids = {}       # id -> count (for duplicate + prefix checks)
        self._callables_per_type = []

    # --- tiny counter helpers (stdlib-only, no imports beyond json/os/re/sys) ---
    def inc(self, key, n=1):
        self.C[key] = self.C.get(key, 0) + n

    def bump(self, group, key, n=1):
        g = self.K.setdefault(group, {})
        g[key] = g.get(key, 0) + n

    def fail(self, key, n=1):
        self.chk[key] = self.chk.get(key, 0) + n

    def mark(self, decision):
        if decision in self.decisions:
            self.decisions[decision] = True

    # --- main ---
    def run(self):
        with open(self.path, "r", encoding="utf-8") as fh:
            doc = json.load(fh)

        self._check_envelope(doc)
        app = doc.get("application", {})
        self._check_identity_segments(app)

        app_id = app.get("id")
        st = app.get("symbol_table", {})
        self.inc("modules", len(st))

        for file_key, module in st.items():
            self._check_symbol_table_key(file_key)
            self._walk_module(file_key, module, app_id)

        self.inc("distinct_ids", len(self._ids))
        return self._emit(doc)

    # Containment invariant: a child node's id must be its parent's id + "/<...>".
    # This is robust to slash-bearing file keys (a module id has extra segments the
    # id grammar doesn't let you recover by string-splitting), unlike a prefix-of-the-id
    # reconstruction. Checked during the walk, where the true parent id is known.
    def _check_containment(self, child_id, parent_id):
        if not child_id or not parent_id:
            return
        if not child_id.startswith(parent_id + "/"):
            self.fail("containment_id_mismatch")

    # --- envelope + identity ---
    def _check_envelope(self, doc):
        if doc.get("schema_version") != SCHEMA_VERSION \
                or doc.get("identity_version") != IDENTITY_VERSION \
                or doc.get("language") != LANGUAGE \
                or doc.get("max_level") != MAX_LEVEL:
            self.fail("envelope_malformed")
        self.C["max_level"] = doc.get("max_level")

    def _check_identity_segments(self, app):
        app_name = app.get("application_name")
        ns = app.get("identity_namespace")
        expected = None
        if app_name is not None and ns is not None:
            # Note: this compares raw values; percent-encoding differences are tolerated here
            # because the grammar check (id_malformed) covers encoding separately.
            expected_tail = f"/{ns}/{app_name}/csharp"
            if not (app.get("id") or "").endswith(expected_tail) \
                    and f"can://{ns}/{app_name}/csharp" != app.get("id"):
                # only a soft structural check; real encoding correctness is id_malformed
                self.fail("identity_segments_inconsistent")

    def _check_symbol_table_key(self, key):
        if os.path.isabs(key) or key.startswith("/"):
            self.fail("symbol_table_key_absolute")
        if ".." in key.split("/"):
            self.fail("symbol_table_key_dotdot")
        if "\\" in key:
            self.fail("symbol_table_key_backslash")

    # --- module walk ---
    def _walk_module(self, file_key, module, app_id):
        source = module.get("source", "")
        self.inc("source_bytes", len(source.encode("utf-8")))
        head = "\n".join(source.splitlines()[:5])
        self.bump("file_class", file_class(file_key, head))

        module_id = module.get("id")
        self._register_id(module_id, kind="module")
        self._check_containment(module_id, app_id)

        types = module.get("types") or {}
        functions = module.get("functions") or {}
        if not types and not functions:
            self.inc("empty_modules")

        for top_type in types.values():
            for type_node, is_nested in iter_types(top_type):
                self._walk_type(module_id, source, type_node, is_nested)

        for callable_node in functions.values():
            self._walk_callable(module_id, source, callable_node)

    def _walk_type(self, parent_id, source, t, is_nested):
        self.inc("types")
        kind = t.get("kind")
        self.bump("types_by_kind", kind)
        if kind in ("record", "record_struct", "delegate"):
            self.mark(kind)
        if is_nested:
            self.mark("nested_type")
        if "`" in (t.get("id") or ""):   # generic arity marker in the id
            self.mark("generic_type")
        if t.get("parts"):
            self.inc("types_with_parts")
            self.mark("parts")

        type_id = t.get("id")
        self._register_id(type_id, kind="type")
        self._check_span(source, t.get("span"), "type")
        # Containment: a top-level type is contained by its module. Nested types are yielded
        # flat today (L1 emits types flat under the module), so their true parent is the
        # enclosing type — not knowable from this flat walk — and we skip the check for them
        # rather than assert a wrong parent.
        if not is_nested:
            self._check_containment(type_id, parent_id)

        callables = t.get("callables") or {}
        self._callables_per_type.append(len(callables))
        for c in callables.values():
            self._walk_callable(type_id, source, c)

        for f in (t.get("fields") or {}).values():
            self._walk_field(type_id, source, f)

    def _walk_callable(self, parent_id, source, c):
        self.inc("callables")
        sig = c.get("signature", "")
        if "#get" in sig:
            self.bump("callables_by_kind", "accessor_get"); self.mark("accessor_get")
        elif "#set" in sig:
            self.bump("callables_by_kind", "accessor_set"); self.mark("accessor_set")
        else:
            self.bump("callables_by_kind", c.get("kind", "method"))

        if c.get("is_async"):
            self.inc("callables_async"); self.mark("is_async")
        if c.get("is_iterator"):
            self.inc("callables_iterator"); self.mark("is_iterator")

        for p in c.get("parameters") or []:
            rk = p.get("ref_kind")
            self.bump("params_by_ref_kind", rk if rk else "(byvalue)")
            if rk in REF_KINDS:
                self.mark(rk)

        callable_id = c.get("id")
        self._register_id(callable_id, kind="callable")
        self._check_span(source, c.get("span"), "callable")
        self._check_containment(callable_id, parent_id)

        # body at L1: call nodes only, callee MUST be null.
        body = c.get("body") or {}
        for bk, bn in body.items():
            self.inc("call_sites")
            if bn.get("kind") != "call":
                self.fail("body_non_call_node_at_l1")
            if bn.get("callee") is not None:
                self.fail("callee_not_null_at_l1")
            self._check_span(source, bn.get("span"), "call")

    def _walk_field(self, parent_id, source, f):
        self.inc("fields")
        kind = f.get("kind")
        self.bump("fields_by_kind", kind)
        if kind in ("property", "event"):
            self.mark(kind)
        field_id = f.get("id")
        self._register_id(field_id, kind="field")
        self._check_span(source, f.get("span"), "field")
        self._check_containment(field_id, parent_id)

    # --- span / D15 byte-slice guard ---
    def _check_span(self, source, span, _kind):
        if not span:
            return
        b = span.get("bytes")
        if not b or len(b) != 2:
            self.fail("span_bytes_malformed"); return
        raw = source.encode("utf-8")
        lo, hi = b
        if lo < 0 or hi < lo or hi > len(raw):
            self.fail("span_bytes_out_of_range"); return
        # D15 guard: the slice must decode as UTF-8 (round-trip). We do not assert it equals
        # a specific declaration string here (that needs the AST); decoding failure is the
        # cheap, oracle-free signal that offsets landed mid-codepoint.
        try:
            raw[lo:hi].decode("utf-8")
        except UnicodeDecodeError:
            self.fail("span_slice_mismatch")

    # --- id registry: grammar + duplicates (containment is checked during the walk) ---
    def _register_id(self, node_id, kind):
        if not node_id:
            self.fail("id_missing"); return
        self._ids[node_id] = self._ids.get(node_id, 0) + 1
        if self._ids[node_id] == 2:
            self.fail("id_duplicate")
        if not ID_ROOT_RE.match(node_id):
            self.fail("id_malformed")

    # --- emit ---
    def _emit(self, doc):
        callables_dist = distribution(self._callables_per_type)
        out = {
            "app": self.label,
            "bytes": os.path.getsize(self.path),
            "max_level": self.C.get("max_level"),
        }
        # scalar counters
        for k in ("modules", "types", "callables", "fields", "call_sites",
                  "source_bytes", "distinct_ids", "empty_modules",
                  "types_with_parts", "callables_async", "callables_iterator"):
            out[k] = self.C.get(k, 0)
        # keyed breakdowns
        out.update(self.K)
        # distributions
        out["callables_per_type"] = callables_dist
        # decision coverage checklist (descriptive: which constructs this app exercises;
        # apps need not implement every C# construct, so there is no "complete" rollup)
        out["decision_coverage"] = self.decisions
        # check_failures: nonzero only (the house convention). Clean run => {}.
        out["check_failures"] = {k: v for k, v in self.chk.items() if v}
        return out


def main(argv):
    if not argv:
        sys.stderr.write(
            "usage: python3 -I l1_metrics.py LABEL=analysis.json [LABEL=PATH ...]\n")
        return 2
    rc = 0
    for arg in argv:
        if "=" in arg:
            label, path = arg.split("=", 1)
        else:
            label, path = os.path.basename(os.path.dirname(arg)) or arg, arg
        try:
            result = L1Analyzer(label, path).run()
        except (OSError, json.JSONDecodeError) as e:
            # A read/parse failure is emitted as a record with a check_failure so the shell
            # still sees a nonzero check and fails the app, rather than the python crashing.
            result = {"app": label, "check_failures": {"input_unreadable": 1},
                      "error": str(e)}
            rc = 1
        sys.stdout.write(json.dumps(result) + "\n")
    return rc


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
